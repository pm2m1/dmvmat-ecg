"""Recording-level metadata audit only; no waveform or predictor access."""

import ast
import csv
import itertools
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

import numpy as np

from dmvmat_ecg.phase2b.contract import digest, file_hash
from dmvmat_ecg.phase2b.preflight import load_metadata
from dmvmat_ecg.phase2c.splits import canonicalize, pattern


def serial_summary(rows, metadata):
    canonical, population = canonicalize(rows)
    grouped = defaultdict(list)
    for r in rows:
        if 18 <= r["age"] <= 89:
            grouped[r["patient_id"]].append(r)
    affected = {p: v for p, v in grouped.items() if len({pattern(r) for r in v}) > 1}
    times = {}
    bad_times = 0
    for pid, records in affected.items():
        for r in records:
            text = metadata[r["ecg_id"]]["recording_date"]
            try:
                times[r["ecg_id"]] = datetime.fromisoformat(text)
            except (ValueError, TypeError):
                times[r["ecg_id"]] = None
                bad_times += 1
    change_counts = Counter()
    record_count = Counter()
    flags = {}
    pairs = Counter()
    spans = []
    for pid, records in affected.items():
        changed = [len({r["y"][j] for r in records if r["observed"][j]}) > 1 for j in (0, 1)]
        change_counts["both" if all(changed) else "CD_only" if changed[0] else "STTC_only"] += 1
        record_count[len(records)] += 1
        valid = [times[r["ecg_id"]] for r in records if times[r["ecg_id"]] is not None]
        if len(valid) == len(records):
            spans.append((max(valid) - min(valid)).total_seconds() / 86400)
            pairs["patients_different_timestamps"] += len(set(valid)) > 1
            pairs["patients_different_dates"] += len({t.date() for t in valid}) > 1
            chosen = min(records, key=lambda r: r["ecg_id"])
            pairs["canonical_not_earliest_timestamp"] += times[chosen["ecg_id"]] != min(valid)
        for a, b in itertools.combinations(records, 2):
            if a["y"] == b["y"]:
                continue
            pairs["discordant_record_pairs"] += 1
            ta, tb = times[a["ecg_id"]], times[b["ecg_id"]]
            if ta is None or tb is None:
                pairs["pair_timestamp_unknown"] += 1
            elif ta == tb:
                pairs["pair_same_timestamp"] += 1
            elif ta.date() == tb.date():
                pairs["pair_same_date_different_time"] += 1
            else:
                pairs["pair_different_dates"] += 1
            pairs["pair_identical_native_hash"] += a["raw_hash"] == b["raw_hash"]
        for field in [
            "validated_by_human",
            "second_opinion",
            "initial_autogenerated_report",
            "validated_by",
        ]:
            vals = [metadata[r["ecg_id"]][field] for r in records]
            if field == "validated_by":
                vals = ["missing" if not str(v).strip() else "present" for v in vals]
            flags.setdefault(field, dict(record_values=Counter(), patients_with_differing_values=0))
            flags[field]["record_values"].update(vals)
            flags[field]["patients_with_differing_values"] += len(set(vals)) > 1
    affected_rows = [r for v in affected.values() for r in v]
    likelihood = {
        label: dict(
            present_records=0,
            unknown_zero_likelihood_records=0,
            likelihood_values=Counter(),
            patients_differing_likelihood_signature=0,
        )
        for label in ["CD", "STTC"]
    }
    for label in likelihood:
        for records in affected.values():
            signatures = []
            for r in records:
                values = metadata[r["ecg_id"]]["likelihoods"][label]
                likelihood[label]["present_records"] += bool(values)
                likelihood[label]["unknown_zero_likelihood_records"] += 0 in values
                likelihood[label]["likelihood_values"].update(map(str, values))
                signatures.append(tuple(sorted(values)))
            likelihood[label]["patients_differing_likelihood_signature"] += len(set(signatures)) > 1
    canonical_map = {r["patient_id"]: r for r in canonical}
    return dict(
        population=population,
        affected_patients=len(affected),
        affected_recordings=len(affected_rows),
        recordings_per_affected_patient=dict(sorted(record_count.items())),
        changes=dict(change_counts),
        invalid_or_missing_timestamps=bad_times,
        timing=dict(pairs),
        within_patient_span_days={
            k: float(v)
            for k, v in zip(
                ["min", "p25", "median", "p75", "max"],
                np.quantile(spans, [0, 0.25, 0.5, 0.75, 1]),
                strict=True,
            )
        }
        if spans
        else {},
        annotation_metadata=flags,
        diagnostic_likelihoods=likelihood,
        canonical_exact_record_labels_verified=all(
            canonical_map[p] == min(v, key=lambda r: r["ecg_id"]) for p, v in grouped.items()
        ),
        affected_record_identity_hash=digest(sorted(r["ecg_id"] for r in affected_rows)),
        individual_records_published=False,
        real_waveform_reads=0,
    )


def audit_release(root):
    root = Path(root)
    rows, provenance = load_metadata(root)
    raw = root / "data/raw/ptbxl_v1_0_3"
    mapping = {}
    with (raw / "scp_statements.csv").open() as f:
        for r in csv.DictReader(f):
            if float(r["diagnostic"] or 0) == 1 and r["diagnostic_class"] in {"CD", "STTC"}:
                mapping[r[""]] = r["diagnostic_class"]
    allowed = {r["ecg_id"]: r for r in rows}
    meta = {}
    with (raw / "ptbxl_database.csv").open() as f:
        for r in csv.DictReader(f):
            # Never decode fold10 diagnostic strings or report content.
            if int(r["strat_fold"]) not in range(1, 10):
                continue
            i = int(r["ecg_id"])
            if i not in allowed:
                continue
            codes = ast.literal_eval(r["scp_codes"])
            y = [int(any(mapping.get(k) == label for k in codes)) for label in ["CD", "STTC"]]
            if y != allowed[i]["y"] or int(float(r["patient_id"])) != allowed[i]["patient_id"]:
                raise PermissionError("Exact recording annotation/cache identity differs")
            meta[i] = {
                k: r[k]
                for k in [
                    "recording_date",
                    "validated_by_human",
                    "second_opinion",
                    "initial_autogenerated_report",
                    "validated_by",
                ]
            }
            meta[i]["likelihoods"] = {
                label: [v for k, v in codes.items() if mapping.get(k) == label]
                for label in ["CD", "STTC"]
            }
    if set(meta) != set(allowed):
        raise PermissionError("Missing authorized metadata")
    summary = serial_summary(rows, meta)
    if summary["affected_patients"] != 625:
        raise PermissionError("Discordance population changed")
    return dict(
        **summary,
        source_provenance=provenance,
        metadata_sha256=file_hash(raw / "ptbxl_database.csv"),
        source_scope="original eligible folds1–9 only; no waveform reads or predictive results",
    )
